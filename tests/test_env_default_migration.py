"""Regression tests for Platform-managed .env default migrations.

In the projectdavid-platform repository, place this file in tests/unit/.
Run: python -m pytest tests/unit/test_env_default_migration.py -q
"""

from __future__ import annotations

import logging
import os
from pathlib import Path

from dotenv import dotenv_values

from projectdavid_platform.start_orchestration import Orchestrator

OLD = "https://api.hyperbolic.xyz/v1"
NEW = "https://api.hyperbolic.ai/inference/v1"
HEADER = "# Auto-generated by projectdavid-platform — test\n"


def _orchestrator() -> Orchestrator:
    # Test the migration without invoking Docker, licensing, or stack bootstrap.
    instance = Orchestrator.__new__(Orchestrator)
    instance.log = logging.getLogger(__name__)
    return instance


def test_packaged_default_is_current():
    assert Orchestrator._DEFAULT_VALUES["HYPERBOLIC_BASE_URL"] == NEW


def test_migrates_old_default_and_preserves_secrets_and_other_settings(tmp_path: Path):
    env = tmp_path / ".env"
    original = (
        HEADER
        + f"HYPERBOLIC_BASE_URL={OLD}\n"
        + "MYSQL_PASSWORD=keep_existing_password\n"
        + "ADMIN_API_KEY=keep_existing_admin_key\n"
        + "TOGETHER_BASE_URL=https://custom-together.example/v1\n"
        + "# user comment must survive\n"
    )
    env.write_text(original, encoding="utf-8")

    _orchestrator()._migrate_generated_env_defaults(env)

    result = dotenv_values(env)
    assert result["HYPERBOLIC_BASE_URL"] == NEW
    assert result["MYSQL_PASSWORD"] == "keep_existing_password"
    assert result["ADMIN_API_KEY"] == "keep_existing_admin_key"
    assert result["TOGETHER_BASE_URL"] == "https://custom-together.example/v1"
    assert "# user comment must survive" in env.read_text(encoding="utf-8")


def test_preserves_custom_endpoint_even_when_generated(tmp_path: Path):
    env = tmp_path / ".env"
    custom = "https://my-proxy.example/inference/v1"
    env.write_text(HEADER + f"HYPERBOLIC_BASE_URL={custom}\n", encoding="utf-8")

    _orchestrator()._migrate_generated_env_defaults(env)

    assert dotenv_values(env)["HYPERBOLIC_BASE_URL"] == custom


def test_does_not_modify_unmanaged_env(tmp_path: Path):
    env = tmp_path / ".env"
    content = f"# My environment\nHYPERBOLIC_BASE_URL={OLD}\n"
    env.write_text(content, encoding="utf-8")

    _orchestrator()._migrate_generated_env_defaults(env)

    assert env.read_text(encoding="utf-8") == content


def test_adds_missing_endpoint_to_generated_env(tmp_path: Path):
    env = tmp_path / ".env"
    env.write_text(HEADER + "MYSQL_USER=existing_user\n", encoding="utf-8")

    _orchestrator()._migrate_generated_env_defaults(env)

    result = dotenv_values(env)
    assert result["HYPERBOLIC_BASE_URL"] == NEW
    assert result["MYSQL_USER"] == "existing_user"


def test_migration_idempotent(tmp_path: Path):
    env = tmp_path / ".env"
    env.write_text(HEADER + f"HYPERBOLIC_BASE_URL={OLD}\n", encoding="utf-8")
    instance = _orchestrator()

    instance._migrate_generated_env_defaults(env)
    once = env.read_bytes()
    instance._migrate_generated_env_defaults(env)

    assert env.read_bytes() == once


def test_existing_runtime_loads_reconciled_value_into_process(
    tmp_path: Path, monkeypatch
):
    env = tmp_path / ".env"
    env.write_text(HEADER + f"HYPERBOLIC_BASE_URL={OLD}\n", encoding="utf-8")
    monkeypatch.chdir(tmp_path)
    monkeypatch.setenv("HYPERBOLIC_BASE_URL", "stale-value-from-shell")

    _orchestrator()._check_for_required_env_file()

    assert os.getenv("HYPERBOLIC_BASE_URL") == NEW
    assert dotenv_values(env)["HYPERBOLIC_BASE_URL"] == NEW


def test_does_not_override_deliberately_blank_value(tmp_path: Path):
    env = tmp_path / ".env"
    env.write_text(HEADER + 'HYPERBOLIC_BASE_URL=""\n', encoding="utf-8")
    _orchestrator()._migrate_generated_env_defaults(env)
    assert dotenv_values(env)["HYPERBOLIC_BASE_URL"] == ""
