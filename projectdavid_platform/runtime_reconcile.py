"""Additive, repeatable reconciliation of existing Project David runtimes.

Local configuration is authoritative. Installed package templates may introduce
new keys, but never silently replace an existing value or an existing secret.
Reconciliation happens on the next ``pdavid`` invocation, not at pip install.
"""

from __future__ import annotations

import base64
import binascii
import logging
import secrets
from collections.abc import Mapping
from pathlib import Path
from typing import Any

import yaml
from dotenv import dotenv_values, set_key

log = logging.getLogger(__name__)

_COMPOSE_OVERLAY_HEADER = "# Generated by projectdavid-platform; do not edit.\n"
_MISSING = object()


class RuntimeReconciliationError(RuntimeError):
    """An upgrade cannot be applied without risking existing runtime state."""


def generate_secret(name: str) -> str:
    """Match Core's instance-secret formats, without importing Core into Platform."""
    if name == "PROJECT_DAVID_CREDENTIAL_KEY":
        # Identical format and entropy to cryptography.Fernet.generate_key().
        return base64.urlsafe_b64encode(secrets.token_bytes(32)).decode("ascii")
    if name == "API_KEY":
        return f"ea_{secrets.token_urlsafe(16)}"
    return secrets.token_hex(32)


def _validate_persistent_secret(name: str, value: str | None) -> None:
    if not value:
        raise RuntimeReconciliationError(
            f"{name} is declared but empty; refusing silent key rotation"
        )
    if name == "PROJECT_DAVID_CREDENTIAL_KEY":
        try:
            raw = base64.urlsafe_b64decode(value.encode("ascii"))
        except (binascii.Error, ValueError, UnicodeEncodeError) as exc:
            raise RuntimeReconciliationError("Invalid Fernet credential key") from exc
        if len(raw) != 32 or base64.urlsafe_b64encode(raw).decode("ascii") != value:
            raise RuntimeReconciliationError("Invalid Fernet credential key")
    if name == "PROJECT_DAVID_PROVIDER_KEY_HMAC_KEY":
        try:
            raw = bytes.fromhex(value)
        except ValueError as exc:
            raise RuntimeReconciliationError(
                "Invalid provider fingerprint key"
            ) from exc
        if len(raw) != 32 or len(value) != 64:
            raise RuntimeReconciliationError("Invalid provider fingerprint key")


def reconcile_env(
    path: Path,
    *,
    generated_names: tuple[str, ...] | list[str],
    defaults: Mapping[str, str],
) -> tuple[str, ...]:
    """Append missing settings only; never replace explicitly supplied values.

    Using python-dotenv's atomic rewrite keeps existing lines/comments in place.
    An explicitly empty or malformed root key is a hard failure, not a request
    to generate replacement cryptographic identity.
    """
    if not path.is_file():
        return ()
    present = dotenv_values(path)
    for name in generated_names:
        if name in present and name in {
            "PROJECT_DAVID_CREDENTIAL_KEY",
            "PROJECT_DAVID_PROVIDER_KEY_HMAC_KEY",
        }:
            _validate_persistent_secret(name, present[name])

    additions: dict[str, str] = {}
    for name in generated_names:
        if name not in present:
            additions[name] = generate_secret(name)
    for name, default in defaults.items():
        if name not in present and name not in additions:
            additions[name] = str(default)

    for name, value in additions.items():
        set_key(str(path), name, value, quote_mode="auto")

    if additions:
        log.info("Backfilled runtime configuration: %s", ", ".join(additions))
    return tuple(additions)


def _environment_missing(desired: Any, current: Any) -> Any:
    """Diff Compose environment/labels keyed mappings or KEY=value lists."""

    def as_map(value: Any) -> dict[str, Any]:
        if isinstance(value, Mapping):
            return dict(value)
        if isinstance(value, list) and all(isinstance(v, str) for v in value):
            return {v.split("=", 1)[0]: v for v in value}
        raise RuntimeReconciliationError("Invalid Compose environment/labels format")

    wanted = as_map(desired)
    existing = as_map(current)
    absent = [key for key in wanted if key not in existing]
    if not absent:
        return _MISSING
    if isinstance(desired, list):
        return [wanted[key] for key in absent]
    return {key: wanted[key] for key in absent}


def _new_elements(desired: Any, existing: Any, path: tuple[str, ...] = ()) -> Any:
    """Return only keys absent in the local Compose file.

    Preserve existing scalars, policies, image pins and list settings. List
    merges other than named environment/labels entries are intentionally manual:
    silently adding ports, binds or capabilities could change runtime security.
    """
    if isinstance(desired, Mapping) and isinstance(existing, Mapping):
        result = {}
        for key, value in desired.items():
            if key not in existing:
                result[key] = value
            else:
                addition = _new_elements(value, existing[key], (*path, str(key)))
                if addition is not _MISSING:
                    result[key] = addition
        return result if result else _MISSING
    if path and path[-1] in ("environment", "labels"):
        return _environment_missing(desired, existing)
    return _MISSING


def reconcile_compose(
    *,
    packaged_compose: str,
    local_compose: Path,
    overlay_path: Path,
) -> bool:
    """Create a generated additive Compose overlay without editing user YAML.

    Returns whether an overlay is required. An existing non-generated file at the
    overlay location is never overwritten. No container restarts occur here.
    """
    if not local_compose.is_file():
        return False
    desired = yaml.safe_load(packaged_compose) or {}
    current = yaml.safe_load(local_compose.read_text(encoding="utf-8")) or {}
    if not isinstance(desired, Mapping) or not isinstance(current, Mapping):
        raise RuntimeReconciliationError("Compose root must be a mapping")

    additions = _new_elements(desired, current)
    new_text = (
        _COMPOSE_OVERLAY_HEADER + yaml.safe_dump(additions, sort_keys=False)
        if additions is not _MISSING
        else None
    )
    if overlay_path.exists():
        existing_text = overlay_path.read_text(encoding="utf-8")
        if not existing_text.startswith(_COMPOSE_OVERLAY_HEADER):
            raise RuntimeReconciliationError(
                f"Refusing to replace unmanaged Compose overlay: {overlay_path}"
            )
        if new_text is None:
            overlay_path.unlink()
            return False
        if existing_text == new_text:
            return True

    if new_text is not None:
        overlay_path.write_text(new_text, encoding="utf-8")
        log.info("Added missing Compose definitions in %s", overlay_path.name)
        return True
    return False


__all__ = [
    "RuntimeReconciliationError",
    "generate_secret",
    "reconcile_env",
    "reconcile_compose",
]
